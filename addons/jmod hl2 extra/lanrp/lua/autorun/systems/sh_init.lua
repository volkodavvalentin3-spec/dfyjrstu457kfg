    local function ReconvertData(data)

        local count = table.Count(data)
        local savedata = {
            count = count,
            build = {}
        }

        for k, v in pairs(data) do
            local build_block = {
                id = k:EntIndex(),
                typ = BuildGetCateg(k:GetModel()),
                model = k:GetModel(),
                support = v.support,
                pos = k:GetPos(),
                ang = k:GetAngles(),
            }

            build_block.childs = {}
            for kk, vv in pairs(v.childs) do
                table.insert(build_block.childs, kk:EntIndex())
            end
            if IsValid(k.Door) then
                build_block.door = {
                    model = k:GetModel()
                }
            end
            savedata.build[build_block.id] = build_block
        end

        return util.TableToJSON( savedata, true )
    end

    local function GetAllBuildable(ent)

        local have_support = false
        local data = {}
        local i = 1

        local function get2(par)
            data[par] = {
                ent = par,
                childs = {},
                support = IsValid(par.Support),
                id = i,
            }

            for child, wel in pairs(par:GetAllConnectedProps()) do
                
                if !child:IsValid() then continue end
                if child:GetClass() != "build_prop" then continue end
                
                i = i + 1
                if !data[child] then
                    data[par]["childs"][child] = true
                    get2(child)
                end
            end
        end

        get2(ent)

        return data
    end

